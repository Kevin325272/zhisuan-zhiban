function source(page) {
  return { chunk_id: `cn_k${String(page).padStart(4, "0")}`, print_page: page };
}

function figure(chapter, number, page, caption) {
  return {
    asset_id: `cn_v8_fig_${chapter}_${number}`,
    figure_label: `图${chapter}.${number}`,
    caption,
    source_chunk_id: source(page).chunk_id,
    confidence: "high",
  };
}

function concept({
  chapter,
  ordinal,
  title,
  objective,
  terms,
  note,
  explanation,
  casePrompt,
  pages,
  prerequisite = [],
  importance = "core",
  noteKind = "reminder",
  primaryFigure = null,
}) {
  return {
    concept_id: `cn_c${String(chapter).padStart(2, "0")}_${String(ordinal).padStart(2, "0")}`,
    title,
    learning_objective: objective,
    prerequisite_concept_ids: prerequisite,
    key_terms: terms,
    learning_note: { kind: noteKind, text: note },
    learning_content: {
      explanation: Array.isArray(explanation) ? explanation : [explanation],
      case_prompt: casePrompt,
      practice_tags: ["计算机网络", ...terms.slice(0, 3)],
    },
    sources: pages.map(source),
    importance,
    review_status: "verified",
    ordinal,
    ...(primaryFigure ? { figure_guidance: { primary: primaryFigure, related: [] } } : {}),
  };
}

function module(chapter, ordinal, title, concepts) {
  return {
    module_id: `cn_m${String(chapter).padStart(2, "0")}_${String(ordinal).padStart(2, "0")}`,
    title,
    ordinal,
    concepts,
  };
}

function chapter(ordinal, title, modules) {
  return {
    chapter_id: `cn_ch${String(ordinal).padStart(2, "0")}`,
    source_chapter: `第${ordinal}章`,
    title,
    ordinal,
    modules,
  };
}

